export function getPortfolioSummary(): PortfolioSummary {
  const portfolioCards = MOCK_CARDS.filter(c => c.inPortfolio);

  const totalValue = portfolioCards.reduce((sum, c) => sum + c.currentPrice * (c.quantity || 1), 0);
  const totalCost = portfolioCards.reduce((sum, c) => sum + (c.purchasePrice || c.currentPrice) * (c.quantity || 1), 0);
  const totalGain = totalValue - totalCost;
  const totalGainPct = (totalGain / totalCost) * 100;

  const dayChange = portfolioCards.reduce((sum, c) => sum + (c.currentPrice * c.priceChange24h / 100) * (c.quantity || 1), 0);
  const dayChangePct = (dayChange / totalValue) * 100;

  const sortedByGain = [...portfolioCards].sort((a, b) => b.priceChange30d - a.priceChange30d);

  return {
    totalValue,
    totalCost,
    totalGain,
    totalGainPct,
    dayChange,
    dayChangePct,
    weekChange: totalValue * 0.048,
    monthChange: totalValue * 0.192,
    cardCount: portfolioCards.length,
    topGainers: sortedByGain.slice(0, 3),
    topLosers: sortedByGain.slice(-2),
  };
}
